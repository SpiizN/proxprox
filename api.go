type API struct {
	store *Store
	token string
}

type upstreamView struct {
	Name    string `json:"name"`
	URL     string `json:"url"`
	HasAuth bool   `json:"has_auth"`
}

type configView struct {
	Version   int            `json:"version"`
	Rules     []Rule         `json:"rules"`
	Upstreams []upstreamView `json:"upstreams"`
	VPNs      []VPN          `json:"vpns"`
}

func redactUpstream(upstream Upstream) (upstreamView, error) {
	u, err := parseUpstreamURL(upstream.URL)
	if err != nil {
		return upstreamView{}, fmt.Errorf("redact upstream %q: %w", upstream.Name, err)
	}
	hasAuth := u.User != nil
	u.User = nil
	return upstreamView{Name: upstream.Name, URL: u.String(), HasAuth: hasAuth}, nil
}

func (api *API) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.URL.Path == "/healthz" && r.Method == http.MethodGet {
		writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
		return
	}
	if !validBearer(r.Header.Get("Authorization"), api.token) {
		w.Header().Set("WWW-Authenticate", `Bearer realm="proxprox"`)
		writeError(w, http.StatusUnauthorized, "missing or invalid API token")
		return
	}
	switch {
	case r.URL.Path == "/v1/config" && r.Method == http.MethodGet:
		state := api.store.snapshot()
		view := configView{Version: state.Version, Rules: state.Rules, VPNs: state.VPNs, Upstreams: make([]upstreamView, 0, len(state.Upstreams))}
		for _, upstream := range state.Upstreams {
			redacted, err := redactUpstream(upstream)
			if err != nil {
				writeError(w, http.StatusInternalServerError, err.Error())
				return
			}
			view.Upstreams = append(view.Upstreams, redacted)
		}
		writeJSON(w, http.StatusOK, view)
	case r.URL.Path == "/v1/resolve" && r.Method == http.MethodGet:
		api.resolve(w, r)
	case r.URL.Path == "/v1/rules":
		api.rules(w, r)
	case strings.HasPrefix(r.URL.Path, "/v1/rules/"):
		api.rule(w, r, strings.TrimPrefix(r.URL.Path, "/v1/rules/"))
	case r.URL.Path == "/v1/upstreams":
		api.upstreams(w, r)
	case strings.HasPrefix(r.URL.Path, "/v1/upstreams/"):
		api.upstream(w, r, strings.TrimPrefix(r.URL.Path, "/v1/upstreams/"))
	case r.URL.Path == "/v1/vpns":
		api.vpns(w, r)
	case strings.HasPrefix(r.URL.Path, "/v1/vpns/"):
		api.vpn(w, r, strings.TrimPrefix(r.URL.Path, "/v1/vpns/"))
	default:
		writeError(w, http.StatusNotFound, "unknown endpoint")
	}
}

func validBearer(header, token string) bool {
	if !strings.HasPrefix(header, "Bearer ") {
		return false
	}
	provided := strings.TrimPrefix(header, "Bearer ")
	return subtle.ConstantTimeCompare([]byte(provided), []byte(token)) == 1
}

func (api *API) resolve(w http.ResponseWriter, r *http.Request) {
	host := strings.TrimSuffix(strings.ToLower(r.URL.Query().Get("host")), ".")
	if err := validateHost(host); err != nil {
		writeError(w, http.StatusBadRequest, fmt.Sprintf("invalid host: %v", err))
		return
	}
	state := api.store.snapshot()
	decision := state.decide(host)
	result := map[string]any{"decision": decision}
	if decision.Upstream != "" {
		upstream, ok := state.getUpstream(decision.Upstream)
		if !ok {
			writeError(w, http.StatusInternalServerError, fmt.Sprintf("rule references missing upstream %q", decision.Upstream))
			return
		}
		redacted, err := redactUpstream(upstream)
		if err != nil {
			writeError(w, http.StatusInternalServerError, err.Error())
			return
		}
		result["upstream"] = redacted
	}
	if decision.VPN != "" {
		vpn, ok := state.getVPN(decision.VPN)
		if !ok {
			writeError(w, http.StatusInternalServerError, fmt.Sprintf("rule references missing VPN %q", decision.VPN))
			return
		}
		result["vpn"] = vpn
	}
	writeJSON(w, http.StatusOK, result)
}

func (api *API) rules(w http.ResponseWriter, r *http.Request) {
	switch r.Method {
	case http.MethodGet:
		state := api.store.snapshot()
		program := r.URL.Query().Get("program_slug")
		if program != "" {
			filtered := make([]Rule, 0)
			for _, rule := range state.Rules {
				if rule.ProgramSlug == program {
					filtered = append(filtered, rule)
				}
			}
			writeJSON(w, http.StatusOK, filtered)
			return
		}
		writeJSON(w, http.StatusOK, state.Rules)
	case http.MethodPost:
		var input Rule
		if !decodeJSON(w, r, &input) {
			return
		}
		if input.ID != "" {
			writeError(w, http.StatusBadRequest, "rule ID is generated by the server")
			return
		}
		id, err := newID()
		if err != nil {
			writeError(w, http.StatusInternalServerError, fmt.Sprintf("generate rule ID: %v", err))
			return
		}
		input.ID = id
		err = api.store.update(func(state *State) error {
			state.Rules = append(state.Rules, input)
			return nil
		})
		if err != nil {
			writeError(w, http.StatusBadRequest, fmt.Sprintf("create rule: %v", err))
			return
		}
		writeJSON(w, http.StatusCreated, input)
	default:
		methodNotAllowed(w, "GET, POST")
	}
}

func (api *API) rule(w http.ResponseWriter, r *http.Request, id string) {
	if id == "" || strings.Contains(id, "/") {
		writeError(w, http.StatusNotFound, "rule not found")
		return
	}
	switch r.Method {
	case http.MethodPut:
		var input Rule
		if !decodeJSON(w, r, &input) {
			return
		}
		if input.ID != "" && input.ID != id {
			writeError(w, http.StatusBadRequest, "rule ID does not match URL")
			return
		}
		input.ID = id
		err := api.store.update(func(state *State) error {
			for i := range state.Rules {
				if state.Rules[i].ID == id {
					state.Rules[i] = input
					return nil
				}
			}
			return errNotFound
		})
		respondMutation(w, err, "update rule", input)
	case http.MethodDelete:
		err := api.store.update(func(state *State) error {
			for i, rule := range state.Rules {
				if rule.ID == id {
					state.Rules = append(state.Rules[:i], state.Rules[i+1:]...)
					return nil
				}
			}
			return errNotFound
		})
		respondDeletion(w, err, "delete rule")
	default:
		methodNotAllowed(w, "PUT, DELETE")
	}
}

func (api *API) upstreams(w http.ResponseWriter, r *http.Request) {
	switch r.Method {
	case http.MethodGet:
		state := api.store.snapshot()
		views := make([]upstreamView, 0, len(state.Upstreams))
		for _, item := range state.Upstreams {
			redacted, err := redactUpstream(item)
			if err != nil {
				writeError(w, http.StatusInternalServerError, err.Error())
				return
			}
			views = append(views, redacted)
		}
		writeJSON(w, http.StatusOK, views)
	case http.MethodPost:
		var input Upstream
		if !decodeJSON(w, r, &input) {
			return
		}
		err := api.store.update(func(state *State) error {
			state.Upstreams = append(state.Upstreams, input)
			return nil
		})
		if err != nil {
			writeError(w, http.StatusBadRequest, fmt.Sprintf("create upstream: %v", err))
			return
		}
		redacted, err := redactUpstream(input)
		if err != nil {
			writeError(w, http.StatusInternalServerError, err.Error())
			return
		}
		writeJSON(w, http.StatusCreated, redacted)
	default:
		methodNotAllowed(w, "GET, POST")
	}
}

func (api *API) upstream(w http.ResponseWriter, r *http.Request, name string) {
	if err := validateIdentifier(name); err != nil {
		writeError(w, http.StatusNotFound, "upstream not found")
		return
	}
	switch r.Method {
	case http.MethodPut:
		var input Upstream
		if !decodeJSON(w, r, &input) {
			return
		}
		if input.Name != name {
			writeError(w, http.StatusBadRequest, "upstream name does not match URL")
			return
		}
		err := api.store.update(func(state *State) error {
			for i := range state.Upstreams {
				if state.Upstreams[i].Name == name {
					state.Upstreams[i] = input
					return nil
				}
			}
			return errNotFound
		})
		if err != nil {
			respondMutation(w, err, "update upstream", nil)
			return
		}
		redacted, redactError := redactUpstream(input)
		if redactError != nil {
			writeError(w, http.StatusInternalServerError, redactError.Error())
			return
		}
		respondMutation(w, nil, "update upstream", redacted)
	case http.MethodDelete:
		err := api.store.update(func(state *State) error {
			for _, rule := range state.Rules {
				if rule.Upstream == name {
					return fmt.Errorf("upstream %q is used by rule %q", name, rule.ID)
				}
			}
			for i, item := range state.Upstreams {
				if item.Name == name {
					state.Upstreams = append(state.Upstreams[:i], state.Upstreams[i+1:]...)
					return nil
				}
			}
			return errNotFound
		})
		respondDeletion(w, err, "delete upstream")
	default:
		methodNotAllowed(w, "PUT, DELETE")
	}
}

